test('saved rate inputs survive a cold page reload', async ({ page }) => {
  await page.getByRole('tab', { name: 'Garage', exact: true }).click();
  await page.getByLabel('Average consumption (L/100 km)', { exact: true }).fill('6,2');
  await page.getByLabel('Fuel price (DKK/L)', { exact: true }).fill('14,80');
  await page.getByRole('button', { name: 'Save settings', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Settings saved', exact: true })).toBeVisible();
  await page.screenshot({ path: 'artifacts/garage.png' });
  await page.reload();
  await page.getByRole('tab', { name: 'Garage', exact: true }).click();
  await expect(page.getByLabel('Average consumption (L/100 km)', { exact: true })).toHaveValue('6.2');
  await expect(page.getByLabel('Fuel price (DKK/L)', { exact: true })).toHaveValue('14.8');
});
test('real geolocation start, pause, resume, finish and persistent history', async ({ page, context }) => {
  await context.grantPermissions(['geolocation']);
  await context.setGeolocation({ latitude: 56.15, longitude: 10.20, accuracy: 4 });
  await page.getByRole('button', { name: 'Start a drive', exact: true }).click();
  await expect(page.getByText('DRIVE IN PROGRESS', { exact: true })).toBeVisible();
  await page.waitForTimeout(1200);
  await context.setGeolocation({ latitude: 56.1502, longitude: 10.20, accuracy: 4 });
  await page.waitForTimeout(1200);
  await page.getByRole('button', { name: 'Pause recording', exact: true }).click();
  await expect(page.getByText('DRIVE PAUSED', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Resume drive', exact: true }).click();
  await expect(page.getByText('DRIVE IN PROGRESS', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Finish and save', exact: true }).click();
  await expect(page.getByText('DRIVING DISPLAY', { exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'Trips', exact: true }).click();
  await expect(page.getByText('1 saved', { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('tab', { name: 'Trips', exact: true }).click();
  await expect(page.getByText('1 saved', { exact: true })).toBeVisible();
});
